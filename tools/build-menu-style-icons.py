def number(value):
    return format(value, '.8f') + 'f'


def path_commands(path):
    tokens = re.findall(r'[A-Za-z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)', path)
    rows = []
    i = 0
    while i < len(tokens):
        command = tokens[i]
        i += 1
        assert command in ('M', 'L', 'C', 'Z'), command
        count = {'M': 2, 'L': 2, 'C': 6, 'Z': 0}[command]
        values = list(map(float, tokens[i:i+count]))
        assert len(values) == count
        assert all(0 <= v <= 9 for v in values), values
        i += count
        rows.append("    {'" + command + "', " + ', '.join(number(v) for v in values + [0]*(6-count)) + '},\n')
    return ''.join(rows)


