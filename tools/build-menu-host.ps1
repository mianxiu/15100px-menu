param([string]$OutputPath)
$ErrorActionPreference = 'Stop'
$menuRoot = Split-Path -Parent $PSScriptRoot
if (!$OutputPath) { $OutputPath = Join-Path $menuRoot 'native/MenuHost.exe' }
$menuCompiler = (Get-Command g++.exe -ErrorAction Stop).Source
$menuVendor = Join-Path $menuRoot 'native/vendor/imgui'
# Seed only characters used in our source; dynamic document/error text is
# added by the renderer before its next frame. Keep new UI labels covered.
$menuGlyphChars = Get-Content -LiteralPath "$menuRoot/native/MenuHost.cpp" -Raw -Encoding utf8
$menuGlyphChars += Get-Content -LiteralPath "$menuRoot/native/ShapeColorEditor.h" -Raw -Encoding utf8
$menuGlyphChars += Get-Content -LiteralPath "$menuRoot/native/PerceptualPicker.h" -Raw -Encoding utf8
$menuGlyphValues = @($menuGlyphChars.ToCharArray() | ForEach-Object { [int]$_ } | Where-Object { $_ -gt 127 } | Sort-Object -Unique)
$menuGlyphHeader = "// Generated by tools/build-menu-host.ps1; do not edit.`nstatic constexpr ImWchar menuStaticGlyphs[] = {" + ($menuGlyphValues -join ',') + "};`n"
$menuGlyphPath = "$menuRoot/native/MenuGlyphs.h"
# An unchanged header may be memory-mapped by indexing tools; do not rewrite it.
if (!(Test-Path -LiteralPath $menuGlyphPath) -or [System.IO.File]::ReadAllText($menuGlyphPath) -ne $menuGlyphHeader) {
    [System.IO.File]::WriteAllText($menuGlyphPath, $menuGlyphHeader, [System.Text.UTF8Encoding]::new($false))
}
$menuSources = @('imgui.cpp','imgui_draw.cpp','imgui_tables.cpp','imgui_widgets.cpp','backends/imgui_impl_win32.cpp','backends/imgui_impl_dx11.cpp') | ForEach-Object { Join-Path $menuVendor $_ }
& $menuCompiler -std=c++17 -O2 -static -mwindows -DUNICODE -D_UNICODE -finput-charset=UTF-8 "-I$menuVendor" "$menuRoot/native/MenuHost.cpp" @menuSources -o "$OutputPath" -ld3d11 -ldcomp -ld3dcompiler -ldxgi -ldwmapi -lgdi32 -limm32 -lole32 -lwindowscodecs -luuid -luser32 -lshell32
if ($LASTEXITCODE -ne 0) { throw 'Dear ImGui menu host build failed.' }
